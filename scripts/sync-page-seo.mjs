import { readFile, writeFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const source = JSON.parse(await readFile(new URL('goalmatic.seo.json', root), 'utf8'))
const pages = Object.fromEntries(Object.entries(source.pages).map(([route, metadata]) => [
  route,
  { title: metadata.title, description: metadata.description, image: metadata.image || source.image }
]))
await writeFile(new URL('composables/pageSeo.js', root), `// Generated by scripts/sync-page-seo.mjs from goalmatic.seo.json.\nexport const pageSeo = ${JSON.stringify(pages, null, 2)}\n`)
